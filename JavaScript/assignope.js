//assignment operators
let a = 10;
let b = 5;

a += b; // a = a + b
console.log("After += : " + a);


a -= b; // a = a - b
console.log("After -= : " + a);


a *= b;
// a *= b; // a = a * b
console.log(a); 

a /= b; // a = a / b
console.log("After /= : " + a);

a %= b; // a = a % b
console.log("After %= : " + a);

a **= b; // a = a ** b
console.log("After **= : " + a);